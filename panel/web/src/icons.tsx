// icons.tsx 内联 SVG 图标集。
//
// 为什么不用图标库：面板要 embed 进 Go 二进制、离线可用，且图标需求是封闭集合
// （约 30 个）。引 lucide-react 会多一个运行时依赖和 8–15 KB 产物，而手写这些
// path 只占几 KB 源码，风格还能完全对齐整站的细描边工程感。
//
// path 取自 Lucide（ISC 许可），统一 24×24 viewBox、stroke 描边、currentColor 着色，
// 颜色一律由外层 CSS 决定，不在图标里写死。

import type { SVGProps } from 'react'

type IconProps = {
  /** 边长（px）。默认 15，与 13px 正文的行高搭配最稳。 */
  size?: number
  className?: string
}

/** 所有图标的公共外壳：统一 viewBox、描边宽度与端点样式。 */
function Svg({ size = 15, className, children, ...rest }: IconProps & SVGProps<SVGSVGElement>) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  )
}

